#!/usr/bin/env node

/**
 * ME-DESIGN Token Exporter
 * Converts preset design tokens into industry standard formats:
 * 1. Tailwind CSS v4 `@theme` block
 * 2. W3C Design Tokens Community Group (DTCG) standard specification JSON
 * 3. Standard CSS Custom Properties (:root { ... })
 * 
 * Usage:
 *   node scripts/export-tokens.js [--preset <name|all>] [--format <tailwind|dtcg|css|all>] [--out <dir>]
 */

const fs = require('fs');
const path = require('path');

const presetsDir = path.join(__dirname, '..', 'presets');

// Parse CLI Arguments
const args = process.argv.slice(2);

if (process.argv.includes('--help') || process.argv.includes('-h')) {
  console.log(`
\x1b[1mME-DESIGN Token Exporter\x1b[0m
\x1b[90mExport preset design tokens to Tailwind v4 @theme, W3C DTCG, or CSS\x1b[0m

\x1b[1mUsage:\x1b[0m
  medesign tokens [export] [options]

\x1b[1mOptions:\x1b[0m
  --preset <apple|tesla|metha|all>   Target preset (default: all)
  --format <tailwind|dtcg|css|all>   Target format (default: all)
  --out <directory>                  Output directory (default: stdout / dist/tokens)
`);
  process.exit(0);
}
let targetPreset = 'all';
let targetFormat = 'all';
let outDir = null;

for (let i = 0; i < args.length; i++) {
  if (args[i] === '--preset' && args[i + 1]) {
    targetPreset = args[++i].toLowerCase();
  } else if (args[i] === '--format' && args[i + 1]) {
    targetFormat = args[++i].toLowerCase();
  } else if (args[i] === '--out' && args[i + 1]) {
    outDir = args[++i];
  }
}

// Discover available presets
const presetFolders = fs.readdirSync(presetsDir, { withFileTypes: true })
  .filter(d => d.isDirectory())
  .map(d => d.name)
  .filter(name => fs.existsSync(path.join(presetsDir, name, 'preset.json')));

const selectedPresets = targetPreset === 'all'
  ? presetFolders
  : presetFolders.filter(p => p.toLowerCase() === targetPreset);

if (selectedPresets.length === 0) {
  console.error(`Error: Preset '${targetPreset}' not found. Available presets: ${presetFolders.join(', ')}`);
  process.exit(1);
}

// Format 1: Tailwind CSS v4 @theme Generator
function toTailwindV4Theme(preset) {
  const lines = ['/* Tailwind CSS v4 @theme configuration */', '/* Generated by ME-DESIGN Token Engine */', '@theme {'];

  // Colors
  if (preset.color) {
    if (preset.color.canvas) lines.push(`  --color-canvas: ${preset.color.canvas};`);
    if (preset.color.surfaceRaised) lines.push(`  --color-surface-raised: ${preset.color.surfaceRaised};`);
    if (preset.color.surfaceInset) lines.push(`  --color-surface-inset: ${preset.color.surfaceInset};`);
    if (preset.color.borderSubtle) lines.push(`  --color-border-subtle: ${preset.color.borderSubtle};`);
    if (preset.color.borderFocus) lines.push(`  --color-border-focus: ${preset.color.borderFocus};`);
    if (preset.color.accent) lines.push(`  --color-accent: ${preset.color.accent};`);
    if (preset.color.accentForeground) lines.push(`  --color-accent-foreground: ${preset.color.accentForeground};`);

    if (preset.color.status) {
      Object.entries(preset.color.status).forEach(([k, v]) => {
        lines.push(`  --color-status-${k}: ${v};`);
      });
    }
  }

  // Typography
  if (preset.typography) {
    if (preset.typography.display) lines.push(`  --font-display: ${preset.typography.display};`);
    if (preset.typography.sans) lines.push(`  --font-sans: ${preset.typography.sans};`);
    if (preset.typography.mono) lines.push(`  --font-mono: ${preset.typography.mono};`);
    if (preset.typography.headingTracking) lines.push(`  --tracking-heading: ${preset.typography.headingTracking};`);
    if (preset.typography.uiLineHeight) lines.push(`  --leading-ui: ${preset.typography.uiLineHeight};`);
    if (preset.typography.proseLineHeight) lines.push(`  --leading-prose: ${preset.typography.proseLineHeight};`);
  }

  // Geometry
  if (preset.geometry) {
    if (preset.geometry.radiusBase) lines.push(`  --radius-base: ${preset.geometry.radiusBase};`);
    if (preset.geometry.radiusOuter) lines.push(`  --radius-outer: ${preset.geometry.radiusOuter};`);
    if (preset.geometry.hitTargetMinTouch) lines.push(`  --hit-target-min: ${preset.geometry.hitTargetMinTouch};`);
  }

  // Motion
  if (preset.motion) {
    if (preset.motion.easingEntry) lines.push(`  --ease-entry: ${preset.motion.easingEntry};`);
    if (preset.motion.easingExit) lines.push(`  --ease-exit: ${preset.motion.easingExit};`);
    if (preset.motion.durationEntry) lines.push(`  --duration-entry: ${preset.motion.durationEntry};`);
    if (preset.motion.durationExit) lines.push(`  --duration-exit: ${preset.motion.durationExit};`);
  }

  lines.push('}');
  return lines.join('\n');
}

function oklchToLinearRgb(l, c, h) {
  const rad = h * Math.PI / 180;
  const a = c * Math.cos(rad);
  const b = c * Math.sin(rad);

  const l1 = l + 0.3963377774 * a + 0.2158037573 * b;
  const m1 = l - 0.1055613458 * a - 0.0638541728 * b;
  const s1 = l - 0.0894841775 * a - 1.2914855480 * b;

  const l_c = l1 * l1 * l1;
  const m_c = m1 * m1 * m1;
  const s_c = s1 * s1 * s1;

  const r_lin = +4.0767434721 * l_c - 3.3077115913 * m_c + 0.2309699292 * s_c;
  const g_lin = -1.2684380046 * l_c + 2.6097574011 * m_c - 0.3413193965 * s_c;
  const b_lin = -0.0041960863 * l_c - 0.7034186147 * m_c + 1.7076147010 * s_c;

  return [r_lin, g_lin, b_lin];
}

function inGamut(r, g, b, eps = 0.0001) {
  return r >= -eps && r <= 1 + eps &&
         g >= -eps && g <= 1 + eps &&
         b >= -eps && b <= 1 + eps;
}

// Convert OKLCH to sRGB Hex using CSS Color 4 Gamut Mapping (binary search chroma reduction)
function oklchToHex(colorStr) {
  if (!colorStr || !colorStr.startsWith('oklch(')) return null;
  const match = colorStr.match(/oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)/i);
  if (!match) return null;
  const l = parseFloat(match[1]);
  const c = parseFloat(match[2]);
  const h = parseFloat(match[3]);

  const [r0, g0, b0] = oklchToLinearRgb(l, c, h);
  let bestRgb = [r0, g0, b0];

  // If outside sRGB gamut, reduce chroma via binary search while preserving lightness and hue angle
  if (!inGamut(r0, g0, b0)) {
    let cLow = 0;
    let cHigh = c;
    for (let i = 0; i < 25; i++) {
      const cMid = (cLow + cHigh) / 2;
      const rgb = oklchToLinearRgb(l, cMid, h);
      if (inGamut(rgb[0], rgb[1], rgb[2])) {
        cLow = cMid;
        bestRgb = rgb;
      } else {
        cHigh = cMid;
      }
    }
  }

  const gamma = (x) => x <= 0.0031308 ? 12.92 * x : 1.055 * Math.pow(Math.max(0, x), 1 / 2.4) - 0.055;
  const R = Math.min(255, Math.max(0, Math.round(gamma(bestRgb[0]) * 255)));
  const G = Math.min(255, Math.max(0, Math.round(gamma(bestRgb[1]) * 255)));
  const B = Math.min(255, Math.max(0, Math.round(gamma(bestRgb[2]) * 255)));

  return '#' + [R, G, B].map(x => x.toString(16).padStart(2, '0')).join('');
}

// Format 2: W3C Design Tokens Community Group (DTCG) Generator
// Supports 'oklch' (modern CSS Color 4) or 'srgb' (hex tokens for Figma / legacy tools)
function toDtcgTokens(preset, colorSpace = 'oklch') {
  const dtcg = {
    $name: preset.name,
    $description: preset.description,
    $version: '2024.1.0',
    color: {},
    fontFamily: {},
    dimension: {},
    duration: {},
    cubicBezier: {}
  };

  // Colors
  if (preset.color) {
    Object.entries(preset.color).forEach(([k, v]) => {
      if (typeof v === 'string') {
        const tokenVal = colorSpace === 'srgb' ? (oklchToHex(v) || v) : v;
        dtcg.color[k] = {
          $value: tokenVal,
          $type: 'color',
          $description: `${k} color token for ${preset.name}`
        };
      } else if (typeof v === 'object') {
        dtcg.color[k] = {};
        Object.entries(v).forEach(([subK, subV]) => {
          const tokenVal = colorSpace === 'srgb' ? (oklchToHex(subV) || subV) : subV;
          dtcg.color[k][subK] = {
            $value: tokenVal,
            $type: 'color',
            $description: `${k}.${subK} color token for ${preset.name}`
          };
        });
      }
    });
  }

  // Typography
  if (preset.typography) {
    ['display', 'sans', 'mono'].forEach(fontKey => {
      if (preset.typography[fontKey]) {
        dtcg.fontFamily[fontKey] = {
          $value: preset.typography[fontKey],
          $type: 'fontFamily',
          $description: `${fontKey} font stack`
        };
      }
    });
    if (preset.typography.headingTracking) {
      dtcg.dimension.headingTracking = {
        $value: preset.typography.headingTracking,
        $type: 'dimension',
        $description: 'Optical negative tracking for headings'
      };
    }
  }

  // Geometry
  if (preset.geometry) {
    if (preset.geometry.radiusBase) {
      dtcg.dimension.radiusBase = {
        $value: preset.geometry.radiusBase,
        $type: 'dimension',
        $description: 'Base corner radius'
      };
    }
    if (preset.geometry.radiusOuter) {
      dtcg.dimension.radiusOuter = {
        $value: preset.geometry.radiusOuter,
        $type: 'dimension',
        $description: 'Outer card corner radius'
      };
    }
    if (preset.geometry.hitTargetMinTouch) {
      dtcg.dimension.hitTargetMin = {
        $value: preset.geometry.hitTargetMinTouch,
        $type: 'dimension',
        $description: 'WCAG 2.5.8 / HIG minimum touch target dimension (44px)'
      };
    }
  }

  // Motion
  if (preset.motion) {
    if (preset.motion.durationEntry) {
      dtcg.duration.entry = {
        $value: preset.motion.durationEntry,
        $type: 'duration',
        $description: 'Entry motion timing'
      };
    }
    if (preset.motion.durationExit) {
      dtcg.duration.exit = {
        $value: preset.motion.durationExit,
        $type: 'duration',
        $description: 'Exit motion timing (asymmetric 0.65x)'
      };
    }
    if (preset.motion.easingEntry) {
      dtcg.cubicBezier.entry = {
        $value: preset.motion.easingEntry,
        $type: 'cubicBezier',
        $description: 'Entry cubic-bezier timing function'
      };
    }
    if (preset.motion.easingExit) {
      dtcg.cubicBezier.exit = {
        $value: preset.motion.easingExit,
        $type: 'cubicBezier',
        $description: 'Exit cubic-bezier timing function'
      };
    }
  }

  return JSON.stringify(dtcg, null, 2);
}

// Format 3: CSS Custom Properties Generator (:root { ... })
function toCssVariables(preset) {
  const lines = ['/* Standard CSS Custom Properties */', '/* Generated by ME-DESIGN Token Engine */', ':root {'];

  if (preset.color) {
    Object.entries(preset.color).forEach(([k, v]) => {
      if (typeof v === 'string') {
        const cssKey = k.replace(/([A-Z])/g, '-$1').toLowerCase();
        lines.push(`  --color-${cssKey}: ${v};`);
      } else if (typeof v === 'object') {
        Object.entries(v).forEach(([subK, subV]) => {
          lines.push(`  --color-${k}-${subK}: ${subV};`);
        });
      }
    });
  }

  if (preset.typography) {
    if (preset.typography.sans) lines.push(`  --font-sans: ${preset.typography.sans};`);
    if (preset.typography.mono) lines.push(`  --font-mono: ${preset.typography.mono};`);
    if (preset.typography.uiLineHeight) lines.push(`  --line-height-ui: ${preset.typography.uiLineHeight};`);
    if (preset.typography.proseLineHeight) lines.push(`  --line-height-prose: ${preset.typography.proseLineHeight};`);
  }

  if (preset.geometry) {
    if (preset.geometry.radiusBase) lines.push(`  --radius-base: ${preset.geometry.radiusBase};`);
    if (preset.geometry.radiusOuter) lines.push(`  --radius-outer: ${preset.geometry.radiusOuter};`);
    if (preset.geometry.hitTargetMinTouch) lines.push(`  --hit-target-min: ${preset.geometry.hitTargetMinTouch};`);
  }

  lines.push('}');
  return lines.join('\n');
}

// Execution CLI Guard
if (require.main === module) {
  const results = [];

  selectedPresets.forEach(presetId => {
    const jsonPath = path.join(presetsDir, presetId, 'preset.json');
    const preset = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));

    const exportItem = {
      preset: presetId,
      name: preset.name,
      outputs: {}
    };

    if (targetFormat === 'tailwind' || targetFormat === 'all') {
      exportItem.outputs.tailwind = toTailwindV4Theme(preset);
    }
    if (targetFormat === 'dtcg' || targetFormat === 'all') {
      exportItem.outputs.dtcgOklch = toDtcgTokens(preset, 'oklch');
      exportItem.outputs.dtcgSrgb = toDtcgTokens(preset, 'srgb');
      exportItem.outputs.dtcg = exportItem.outputs.dtcgOklch;
    }
    if (targetFormat === 'css' || targetFormat === 'all') {
      exportItem.outputs.css = toCssVariables(preset);
    }

    results.push(exportItem);
  });

  // Output Handling
  if (outDir) {
    if (!fs.existsSync(outDir)) {
      fs.mkdirSync(outDir, { recursive: true });
    }

    results.forEach(res => {
      if (res.outputs.tailwind) {
        fs.writeFileSync(path.join(outDir, `${res.preset}-theme.css`), res.outputs.tailwind, 'utf8');
      }
      if (res.outputs.dtcgOklch) {
        fs.writeFileSync(path.join(outDir, `${res.preset}-tokens.oklch.json`), res.outputs.dtcgOklch, 'utf8');
        fs.writeFileSync(path.join(outDir, `${res.preset}-tokens.dtcg.json`), res.outputs.dtcgOklch, 'utf8');
      }
      if (res.outputs.dtcgSrgb) {
        fs.writeFileSync(path.join(outDir, `${res.preset}-tokens.srgb.json`), res.outputs.dtcgSrgb, 'utf8');
      }
      if (res.outputs.css) {
        fs.writeFileSync(path.join(outDir, `${res.preset}-tokens.css`), res.outputs.css, 'utf8');
      }
    });

    console.log(`Successfully exported tokens for [${selectedPresets.join(', ')}] into '${outDir}'.`);
  } else {
    // Stdout
    results.forEach(res => {
      console.log(`\n========================================`);
      console.log(`PRESET: ${res.name} (${res.preset})`);
      console.log(`========================================\n`);
      if (res.outputs.tailwind) {
        console.log(`--- [Tailwind v4 @theme] ---`);
        console.log(res.outputs.tailwind);
        console.log('');
      }
      if (res.outputs.dtcgOklch) {
        console.log(`--- [W3C DTCG Format JSON (OKLCH Native)] ---`);
        console.log(res.outputs.dtcgOklch);
        console.log('');
      }
      if (res.outputs.dtcgSrgb) {
        console.log(`--- [W3C DTCG Format JSON (sRGB Gamut-Mapped Hex)] ---`);
        console.log(res.outputs.dtcgSrgb);
        console.log('');
      }
      if (res.outputs.css) {
        console.log(`--- [CSS Custom Properties] ---`);
        console.log(res.outputs.css);
        console.log('');
      }
    });
  }
}

module.exports = {
  oklchToHex,
  oklchToLinearRgb,
  inGamut,
  toTailwindV4Theme,
  toDtcgTokens,
  toCssVariables
};
